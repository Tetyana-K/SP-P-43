async Task PrintLettersAsync(char start, char end)
{
    for (char c = start; c <= end; c++)
    {
        Console.WriteLine($"\t" + c);
        await Task.Delay(100);// Затримка для наочності
    }
}
/*
 Task.WaitAll(...) або task.Wait() — синхронні методи. Вони змушують викликаючий потік  сидіти і чекати.

await Task.WhenAll(...) або await task — асинхронні. 
    Вони відпускають потік робити інші корисні справи, поки завдання виконуються у фоні.
*/