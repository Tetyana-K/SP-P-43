// async(Приготуйся!)
//Це  знак для компілятора, який ставиться біля назви методу.
//Він каже: «У цьому методі буде асинхронна робота, приготуйся розрізати код на частини».
//Сам по собі async нічого у фоні не запускає.

//await (Запусти і звільни потік!)
//Це команда для потоку програми. Вона ставиться перед важкою задачею і каже потоку:
//«Запусти цю задачу, але не стій над нею. Йди роби інші справи (щоб програма не зависала).
//Коли задача закінчиться — будь-який вільний потік повернеться і дочитає код далі».

// Аналогія на кухні:
//  async — це наше рішення готувати каву та тости одночасно,
//  а await — це момент, коли ви увімкнули чайник і пішли вмиватися, замість того, щоб чекати доки чайник закипить.

// СПОСІБ 1: Створення -> Запуск
// Створення Task через конструктор і Start
// Примітка: Використовується рідко, коли треба розділити створення і старт.

// Приклад використання різних способів запуску завдань (Task) в C#
Task task1 = new Task(PrintHelloAsync); // створюємо завдання, яке виконає метод PrintHello
task1.Start(); // запускаємо завдання

//task1.Wait(); // чекаємо завершення першого завдання, блокуючи потік

// СПОСІБ 2: Створення і запуск Task через Task.Run (Сучасний стандарт)
// Найкращий вибір для важких обчислень у фоні

Task task2 = Task.Run(PrintNumbersAsync); // створюємо і запускаємо завдання, яке виконає метод PrintNumbers
//task2.Wait(); // чекаємо завершення другого завдання, блокуючи потік

//СПОСІБ 3: Створення і запуск Task через TaskFactory
// Потужний, але низькорівневий інструмент. Потребує обережності з async/await.

TaskFactory taskFactory = new TaskFactory(); // створюємо фабрику завдань
//Task task3 = taskFactory.StartNew(() => PrintLettersAsync('a', 'e'));
Task task3 = taskFactory.StartNew(() => PrintLettersAsync('a', 'e')).Unwrap();
// створюємо і запускаємо завдання,
// Використовуємо .Unwrap(), щоб правильно обробити асинхронний метод всередині StartNew                                                               // яке виконає метод PrintLetters з параметрами

// СПОСІБ 4: Безпосередній await "на місці"
// сучасним стандартом є Task.Run()
await Task.Run(PrintByeAsync); // створюємо і запускаємо завдання, яке виконає метод PrintBye, чекаємо його завершення
                               // БЕЗ блокування потоку

//task1.Wait(); // чекаємо завершення першого завдання
//Task.WaitAll(task1, task2, task3); // чекаємо завершення всіх завдань

// Асинхронне неблокуюче очікування кількох задач одночасно:
await Task.WhenAll(task2, task3);

