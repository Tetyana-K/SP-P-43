Потік (Thread) — це найменша одиниця виконання, яку операційна система може ізольовано запустити та запланувати.
Кожна програма в C# починається з одного головного потоку (Main thread).

! Якщо запустити важке обчислення в головному потоці (наприклад, обробку великого фото у WPF чи WinForms додатку), 
інтерфейс програми "зависне". Щоб цього не сталося, таку роботу виносять у фонові потоки.

Thread (потік) - обгортка  над потоком операційної системи, кожному потоку відповідає один потік ОС (зі своїм стеком), який виконує код.
- Потік — спрощена одиниця виконання (lightweight execution unit),
це послідовність команд, яка виконується всередині процесу.
- В одному процесі може існувати кілька потоків, і вони СПІЛЬНО використовують ресурси процесу,такі як 
    пам’ять, відкриті дескриптори та контекст безпеки.
- Кожен потік має ВЛАСНИЙ стек виконання, лічильник програм (Program Counter), який вказує адресу наступної 
    команди для виконання, та набір регістрів процесора. 
Завдяки цьому потоки можуть виконувати код незалежно один від одного, навіть перебуваючи в межах одного процесу.

- Потоки ефективніше створювати та керувати ними, ніж процеси, завдяки спільним ресурсам, відсутності ізоляції пам’яті
та швидшому перемиканню контексту, ніж між процесами.
 */

