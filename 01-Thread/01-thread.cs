//th.IsBackground = true; // встановлення потока як фоновий (background thread), який буде автоматично завершений
Thread thread = new Thread(PrintLetters); // створення нового потоку, який виконує метод PrintLetters
thread.Name = "MyThread-02"; // встановлення імені потока для зручності відладки
thread.Priority = ThreadPriority.Highest;
thread.IsBackground = true; // встановлення потока як фоновий (background thread), який буде автоматично завершений
//при завершенні основного потока

thread.Start(); // запуск потоку,  метод PrintLetters почне виконуватись паралельно з основним потоком

for (int i = 0; i < 30; i++) // основний потік = Main thread
{
    Console.WriteLine($"Hello in main {i}");
    Thread.Sleep(50); // затримка основного потоку на 100 мс для наочності/ перемикання потоків для наочності
}
void PrintLetters() // метод, який буде виконуватися у вторинному (дочірньому) потоці
{
    for (char c = 'A'; c <= 'Z'; c++)
    {
        Console.WriteLine($"\t\t\t{c} in thread {Thread.CurrentThread.Name} {Thread.CurrentThread.ManagedThreadId}");
        Thread.Sleep(100); //затримка вторинного потоку на 100 мс для наочності
    }
}

Console.WriteLine("____________End Main");